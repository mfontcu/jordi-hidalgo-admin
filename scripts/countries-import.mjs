// Imports the country list of the Flutter phone field (package country_code_picker 3.4.1, through
// app_ui's RegisterCountryCodePicker): src/shared/lib/countries.gen.ts with each country's code,
// dial code, and name in es, ca, and en, in the package's order, and src/shared/ui/kit/flags/ with
// its flag images. Run once per package update:
//   node scripts/countries-import.mjs [path to country_code_picker]
// The default path is the package in the pub cache.
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '3.4.1';
const root = fileURLToPath(new URL('..', import.meta.url));
const packageDir =
  process.argv[2] ?? resolve(homedir(), `.pub-cache/hosted/pub.dev/country_code_picker-${VERSION}`);
const outputPath = resolve(root, 'src/shared/lib/countries.gen.ts');
const flagsDir = resolve(root, 'src/shared/ui/kit/flags');
const LOCALES = ['es', 'ca', 'en'];

if (!existsSync(packageDir)) {
  console.error(`country_code_picker not found at ${packageDir}`);
  process.exit(1);
}

// `codes` in lib/src/country_codes.dart: one map per country, written as Dart literals.
const source = readFileSync(resolve(packageDir, 'lib/src/country_codes.dart'), 'utf8');
const entries = [...source.matchAll(/\{([^{}]*)\}/g)].map((match) => {
  const field = (name) => new RegExp(`"${name}":\\s*"([^"]*)"`).exec(match[1])?.[1];
  return { code: field('code'), dial: field('dial_code'), name: field('name') };
});

const translations = Object.fromEntries(
  LOCALES.map((locale) => [
    locale,
    JSON.parse(readFileSync(resolve(packageDir, `lib/src/i18n/${locale}.json`), 'utf8')),
  ]),
);

// CountryLocalizations stores each value with toString(), so a list of names reads "[A, B]";
// CountryCode.toCountryStringOnly removes the brackets and keeps the part before the first comma.
const clean = (name) =>
  (Array.isArray(name) ? `[${name.join(', ')}]` : name).replace(/[[\]]/g, '').split(',')[0];

const errors = [];
const lines = [];
rmSync(flagsDir, { recursive: true, force: true });
mkdirSync(flagsDir, { recursive: true });
for (const { code, dial, name } of entries) {
  if (!code || !dial || !name) {
    errors.push(`incomplete entry: ${JSON.stringify({ code, dial, name })}`);
    continue;
  }
  const names = LOCALES.map((locale) => clean(translations[locale][code] ?? name));
  const flag = resolve(packageDir, `flags/${code.toLowerCase()}.png`);
  if (!existsSync(flag)) errors.push(`${code}: no flag`);
  else copyFileSync(flag, resolve(flagsDir, `${code.toLowerCase()}.png`));
  lines.push(`  ['${code}', '${dial}', ${names.map((value) => JSON.stringify(value)).join(', ')}],`);
}

if (errors.length > 0) {
  console.error(errors.join('\n'));
  process.exit(1);
}

writeFileSync(
  outputPath,
  `// Generated by scripts/countries-import.mjs from country_code_picker ${VERSION}. Do not edit.
// Code, dial code, and the name in es, ca, and en, in the package's order (the picker's order).

export const COUNTRY_ROWS: readonly (readonly [code: string, dial: string, es: string, ca: string, en: string])[] = [
${lines.join('\n')}
];
`,
);
console.log(`${lines.length} countries`);
