// Generates src/shared/ui/icons/icons.gen.ts from icons.json: one SVG path per icon, taken from
// @material-symbols/svg-400, so the bundle carries only the icons the panel uses.
// `--check` fails instead of writing when the committed file is out of date (run by CI).
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const manifestPath = resolve(root, 'src/shared/ui/icons/icons.json');
const outputPath = resolve(root, 'src/shared/ui/icons/icons.gen.ts');
const symbolsDir = resolve(root, 'node_modules/@material-symbols/svg-400');
const STYLES = new Set(['outlined', 'rounded']);

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const errors = [];
const lines = [];

for (const name of Object.keys(manifest)
  .filter((key) => !key.startsWith('$'))
  .sort()) {
  const { symbol, style } = manifest[name];
  if (!STYLES.has(style)) {
    errors.push(`${name}: unknown style "${style}"`);
    continue;
  }
  let svg;
  try {
    svg = readFileSync(resolve(symbolsDir, style, `${symbol}.svg`), 'utf8');
  } catch {
    errors.push(`${name}: no Material Symbol "${symbol}" in style "${style}"`);
    continue;
  }
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((match) => match[1]);
  if (paths.length !== 1 || !svg.includes('viewBox="0 -960 960 960"')) {
    errors.push(`${name}: unexpected SVG shape in ${style}/${symbol}.svg`);
    continue;
  }
  lines.push(`  ${name}: '${paths[0]}',`);
}

if (errors.length > 0) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const output = `// Generated by scripts/icons-generate.mjs from icons.json. Do not edit.
// Material Symbols (Apache-2.0), weight 400, viewBox 0 -960 960 960.
export const iconPaths = {
${lines.join('\n')}
} as const;

export type IconName = keyof typeof iconPaths;
`;

if (process.argv.includes('--check')) {
  if (readFileSync(outputPath, 'utf8') !== output) {
    console.error('src/shared/ui/icons/icons.gen.ts is out of date: run `npm run icons:generate`.');
    process.exit(1);
  }
  console.log(`Icons check passed: ${lines.length} icons.`);
} else {
  writeFileSync(outputPath, output);
  console.log(`Wrote ${lines.length} icons to src/shared/ui/icons/icons.gen.ts.`);
}
